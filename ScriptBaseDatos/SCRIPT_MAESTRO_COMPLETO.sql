CREATE OR REPLACE PACKAGE BODY PKG_ADMINISTRADOR AS
    FUNCTION function_login_admin(p_email IN VARCHAR2, p_contrasena IN VARCHAR2) RETURN NUMBER IS
        v_id NUMBER;
    BEGIN
        SELECT id_administrador INTO v_id
        FROM administrador
        WHERE UPPER(email_administrador) = UPPER(p_email)
          AND contrasena_administrador = p_contrasena;
        RETURN v_id;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN NULL;
    END function_login_admin;
END PKG_ADMINISTRADOR;
/

-- PKG_CUENTA
CREATE OR REPLACE PACKAGE PKG_CUENTA AS
    FUNCTION function_login_cuenta(p_email IN VARCHAR2, p_contrasena IN VARCHAR2) RETURN NUMBER;
    PROCEDURE procedure_cambiar_saldo(p_id_cuenta IN NUMBER, p_monto IN NUMBER);
END PKG_CUENTA;
/

CREATE OR REPLACE PACKAGE BODY PKG_CUENTA AS
    FUNCTION function_login_cuenta(p_email IN VARCHAR2, p_contrasena IN VARCHAR2) RETURN NUMBER IS
        v_id_cuenta NUMBER;
    BEGIN
        SELECT c.id_cuenta INTO v_id_cuenta
        FROM cuenta c JOIN cliente cli ON cli.id_cliente = c.id_cliente
        WHERE UPPER(cli.email_cliente) = UPPER(p_email)
          AND c.contrasena_cuenta = p_contrasena
          AND c.estado_cuenta = 'activa';
        RETURN v_id_cuenta;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN NULL;
    END function_login_cuenta;

    PROCEDURE procedure_cambiar_saldo(p_id_cuenta IN NUMBER, p_monto IN NUMBER) IS
        v_saldo NUMBER;
    BEGIN
        SELECT saldo_cuenta INTO v_saldo FROM cuenta WHERE id_cuenta = p_id_cuenta;
        IF v_saldo + p_monto < 0 THEN
            RAISE_APPLICATION_ERROR(-20005, 'El saldo no puede quedar negativo.');
        END IF;
        UPDATE cuenta
        SET saldo_cuenta = v_saldo + p_monto,
            fecha_ultima_transaccion_cuenta = SYSTIMESTAMP
        WHERE id_cuenta = p_id_cuenta;
    END procedure_cambiar_saldo;
END PKG_CUENTA;
/

-- PKG_SUCURSAL
CREATE OR REPLACE PACKAGE PKG_SUCURSAL AS
    PROCEDURE procedure_listar_sucursales(o_cursor OUT SYS_REFCURSOR);
    FUNCTION function_crear_sucursal(p_nombre IN VARCHAR2, p_direccion IN VARCHAR2, 
                                    p_telefono IN VARCHAR2, p_id_admin IN NUMBER) RETURN NUMBER;
END PKG_SUCURSAL;
/

CREATE OR REPLACE PACKAGE BODY PKG_SUCURSAL AS
    PROCEDURE procedure_listar_sucursales(o_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN o_cursor FOR
            SELECT id_sucursal, nombre_sucursal, direccion_sucursal, telefono_sucursal,
                   estado_sucursal, id_administrador FROM sucursal ORDER BY id_sucursal;
    END procedure_listar_sucursales;

    FUNCTION function_crear_sucursal(p_nombre IN VARCHAR2, p_direccion IN VARCHAR2, 
                                    p_telefono IN VARCHAR2, p_id_admin IN NUMBER) RETURN NUMBER IS
        PRAGMA AUTONOMOUS_TRANSACTION;
        v_new_id NUMBER;
    BEGIN
        SELECT NVL(MAX(id_sucursal), 0) + 1 INTO v_new_id FROM sucursal;
        INSERT INTO sucursal (id_sucursal, nombre_sucursal, direccion_sucursal, 
                            telefono_sucursal, estado_sucursal, id_administrador)
        VALUES (v_new_id, p_nombre, p_direccion, p_telefono, 'abierta', p_id_admin);
        COMMIT;
        RETURN v_new_id;
    EXCEPTION
        WHEN OTHERS THEN ROLLBACK; RAISE;
    END function_crear_sucursal;
END PKG_SUCURSAL;
/

