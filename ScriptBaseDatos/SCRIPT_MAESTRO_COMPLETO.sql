-- Trigger: Auditoría en CUENTA
CREATE OR REPLACE TRIGGER TRG_CUENTA_AUDIT_UPDATE
AFTER UPDATE ON CUENTA FOR EACH ROW
BEGIN
    IF :OLD.SALDO_CUENTA <> :NEW.SALDO_CUENTA THEN
        INSERT INTO AUDITORIA_CAMBIOS (ID_AUDITORIA, TABLA_AFECTADA, ID_REGISTRO, 
            CAMPO_MODIFICADO, VALOR_ANTERIOR, VALOR_NUEVO, TIPO_OPERACION, USUARIO_ORACLE)
        VALUES (SEQ_AUDITORIA.NEXTVAL, 'CUENTA', TO_CHAR(:NEW.ID_CUENTA), 'SALDO_CUENTA', 
                TO_CHAR(:OLD.SALDO_CUENTA), TO_CHAR(:NEW.SALDO_CUENTA), 'UPDATE', USER);
    END IF;
END;
/

-- Trigger: Validar email único antes de insertar
CREATE OR REPLACE TRIGGER TRG_CLIENTE_BEFORE_INSERT
BEFORE INSERT ON CLIENTE FOR EACH ROW
DECLARE
    v_email_existe NUMBER;
    v_cedula_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_email_existe FROM CLIENTE 
    WHERE UPPER(EMAIL_CLIENTE) = UPPER(:NEW.EMAIL_CLIENTE);
    
    IF v_email_existe > 0 THEN
        RAISE_APPLICATION_ERROR(-20010, 'El email ya existe: ' || :NEW.EMAIL_CLIENTE);
    END IF;
    
    SELECT COUNT(*) INTO v_cedula_existe FROM CLIENTE 
    WHERE CEDULA_CLIENTE = :NEW.CEDULA_CLIENTE;
    
    IF v_cedula_existe > 0 THEN
        RAISE_APPLICATION_ERROR(-20011, 'La cédula ya existe: ' || :NEW.CEDULA_CLIENTE);
    END IF;
    
    IF :NEW.FECHA_REGISTRO_CLIENTE IS NULL THEN
        :NEW.FECHA_REGISTRO_CLIENTE := SYSTIMESTAMP;
    END IF;
END;
/

