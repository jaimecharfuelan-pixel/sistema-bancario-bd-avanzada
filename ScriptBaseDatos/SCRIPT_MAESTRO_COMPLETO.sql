CREATE OR REPLACE PACKAGE BODY PKGC_PRESTAMOS AS
    PROCEDURE procedure_actualizar_saldo(p_id_prestamo IN NUMBER) IS
        v_monto_ini NUMBER;
        v_abonos NUMBER;
        v_cuotas NUMBER;
        v_nuevo NUMBER;
    BEGIN
        SELECT monto_prestamo INTO v_monto_ini FROM prestamo WHERE id_prestamo = p_id_prestamo;
        SELECT NVL(SUM(monto_abono), 0) INTO v_abonos FROM abono_extraordinario WHERE id_prestamo = p_id_prestamo;
        SELECT NVL(SUM(capital_cuota), 0) INTO v_cuotas FROM cuota 
        WHERE id_prestamo = p_id_prestamo AND estado_cuota = 'pagada';
        v_nuevo := v_monto_ini - (v_abonos + v_cuotas);
        IF v_nuevo < 0 THEN v_nuevo := 0; END IF;
        UPDATE prestamo SET saldo_prestamo = v_nuevo, fecha_ultimo_pago_prestamo = SYSTIMESTAMP
        WHERE id_prestamo = p_id_prestamo;
    END procedure_actualizar_saldo;
END PKGC_PRESTAMOS;
